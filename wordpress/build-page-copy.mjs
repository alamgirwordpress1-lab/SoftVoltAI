/**
 * Writes wordpress/softvolt-headless/inc/page-copy-data.php from the page
 * definitions in content/copy — the list of every editable word on the
 * designed pages, which inc/page-copy.php turns into ACF fields.
 *
 * Run from the repo root, then rebuild the theme file:
 *   node --experimental-strip-types --import ./wordpress/alias-loader.mjs wordpress/build-page-copy.mjs
 *   node wordpress/build-functions.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const { pageCopies } = await import("@/content/copy/index");

const pages = pageCopies.map((page) => ({
  slug: page.slug,
  id: page.slug.replace(/-/g, "_"),
  title: page.title,
  sections: Object.entries(page.sections).map(([key, section]) => ({
    key,
    title: section.title,
    help: section.help ?? "",
    fields: Object.entries(section.fields).map(([fieldKey, field]) => {
      const base = { key: fieldKey, kind: field.kind, label: field.label, help: field.help ?? "", value: field.value };
      if (field.kind === "para") return { ...base, rows: field.rows ?? 3 };
      if (field.kind === "items") {
        return {
          ...base,
          item: field.item,
          slots: field.slots,
          sub: Object.entries(field.fields).map(([subKey, sub]) => ({ key: subKey, label: sub.label, kind: sub.kind })),
        };
      }
      return base;
    }),
  })),
}));

// ACF keys are built from these names; a double underscore is reserved for the
// generated ones, and no two fields in a section may produce the same name.
for (const page of pages) {
  for (const section of page.sections) {
    const names = new Set();
    for (const field of section.fields) {
      if (field.key.includes("__")) throw new Error(`${page.slug}.${section.key}.${field.key}: double underscores are reserved`);
      const produced = field.kind === "items" ? Array.from({ length: field.slots }, (_, i) => `${field.key}_${i + 1}`) : [field.key];
      for (const name of produced) {
        if (names.has(name)) throw new Error(`${page.slug}.${section.key}: two fields are called ${name}`);
        names.add(name);
      }
    }
  }
}

// One page per line: readable in the theme editor, and a change to one page is a one-line diff.
const json = `[\n${pages.map((p) => JSON.stringify(p)).join(",\n")}\n]`;
// PHP ends a nowdoc at any line that starts with its marker, not only at "JSON);"
if (/^\s*JSON\b/m.test(json)) throw new Error("a line of the data starts with the nowdoc terminator");

const php = `<?php
/**
 * GENERATED by wordpress/build-page-copy.mjs from content/copy/*.ts — do not edit
 * here. Change the page definition in the front-end repo and run the build.
 */

declare(strict_types=1);

if (!defined('ABSPATH')) {
    exit;
}

if (!defined('SOFTVOLT_PAGE_COPY')) {
    define('SOFTVOLT_PAGE_COPY', <<<'JSON'
${json}
JSON);
}
`;

const out = path.join(here, "softvolt-headless", "inc", "page-copy-data.php");
fs.writeFileSync(out, php);

const fields = pages.reduce((n, p) => n + p.sections.reduce((m, s) => m + s.fields.reduce((k, f) => k + (f.kind === "items" ? f.slots * f.sub.length : f.kind === "link" ? 2 : 1), 0), 0), 0);
console.log(`${out}\n${pages.length} pages, ${pages.reduce((n, p) => n + p.sections.length, 0)} sections, ${fields} inputs, ${php.length} chars`);
